#!/usr/bin/env node
/**
 * Compiles scripts/schema.sql into the baseline migration's SQL module.
 *
 * Hostinger prunes the deployed directory down to what the Node runtime needs
 * — .next, node_modules, package.json, public — so scripts/ does not exist on
 * the server after a build. Migrations therefore run from inside the app
 * (src/instrumentation.ts), and everything they read has to be *compiled
 * into* the bundle rather than read off disk at runtime.
 *
 * schema.sql is the frozen baseline (migration 0001). Schema changes after it
 * are new files in src/server/migrations/, never edits to schema.sql. This
 * runs on `prebuild`, so the generated module cannot drift from the .sql.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const sql = readFileSync(join(here, 'schema.sql'), 'utf8');

const out = `// GENERATED by scripts/bundle-schema.mjs from scripts/schema.sql.
// Do not edit. schema.sql is the frozen baseline: schema changes go in a new
// file under src/server/migrations/, not here and not in the .sql.

export const BASELINE_SQL = ${JSON.stringify(sql)};
`;

const target = join(here, '..', 'src', 'server', 'migrations', '0001_baseline.sql.ts');
const previous = (() => {
  try {
    return readFileSync(target, 'utf8');
  } catch {
    return null;
  }
})();

if (previous === out) {
  console.log('0001_baseline.sql.ts is up to date');
} else {
  writeFileSync(target, out);
  console.log(`Wrote src/server/migrations/0001_baseline.sql.ts (${sql.length} bytes of SQL)`);
}
